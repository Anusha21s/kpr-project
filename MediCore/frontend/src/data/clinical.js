export const getPatientsForUser = (staffRef) =>
  CLINICAL_PATIENTS.filter(
    (patient) => patient.assignedDoctors.includes(staffRef) || patient.assignedNurses.includes(staffRef),
  );

export const getTasksForRole = (role, staffRef) =>
  CLINICAL_TASKS.filter(
    (task) => task.roles.includes(role) && (task.assignedTo.includes(staffRef) || task.assignedTo.length === 0),
  );
